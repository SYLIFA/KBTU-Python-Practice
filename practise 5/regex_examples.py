import re

text = "The rain in Spain falls mainly in the plain! 123-456. Apple, Banana, Cherry."

# 1. Поиск слов, начинающихся на заглавную букву
print("1. Заглавные слова:", re.findall(r"\b[A-Z][a-z]*\b", text))

# 2. Поиск чисел с дефисом
print("2. Числа с дефисом:", re.search(r"\d{3}-\d{3}", text).group())

# 3. Найти все слова, заканчивающиеся на 'ly'
print("3. Слова на 'ly':", re.findall(r"\w+ly\b", text))

# 4. Разбить текст по знакам препинания (точка, запятая, воскл. знак)
print("4. Split по пунктуации:", re.split(r"[,.!\s]+", text))

# 5. Проверка: начинается ли строка с 'The'
print("5. Начало на 'The':", bool(re.match(r"The", text)))

# 6. Замена всех цифр на символ '#'
print("6. Анонимизация цифр:", re.sub(r"\d", "#", text))

# 7. Найти слова ровно из 5 букв
print("7. Слова из 5 букв:", re.findall(r"\b\w{5}\b", text))

# 8. Поиск слов, НЕ содержащих букву 'a' (используем множества)
# (Для краткости примера найдем слова из букв кроме 'a' в начале)
print("8. Поиск без 'a' (фрагменты):", re.findall(r"\b[^a\s]+\b", text))

# 9. Использование групп для захвата фруктов
print("9. Фрукты через группы:", re.findall(r"(Apple|Banana|Cherry)", text))

# 10. Поиск совпадения в конце строки (слово 'Cherry' перед точкой)
print("10. Конец строки:", bool(re.search(r"Cherry\.$", text)))