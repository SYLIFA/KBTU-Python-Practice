import os # Подключаем базовый модуль Python для работы с операционной системой

filename = "sample.txt" # Создаем переменную строкового типа (string) с именем файла

# with - это менеджер контекста. Он гарантирует, что файл закроется автоматически.
# open() открывает файл. "w" (write) - режим записи: создает файл или стирает старый.
# encoding="utf-8" - кодировка, чтобы русские символы читались без ошибок.
# as file - мы даем открытому файлу системное имя 'file' для использования внутри блока.
with open(filename, "w", encoding="utf-8") as file:
    # Метод .write() помещает текст в файл. 
    # \n - это спецсимвол переноса на новую строчку (как нажатие Enter).
    file.write("Первая строка: Привет!\n")
    file.write("Вторая строка: Учим Python.\n")

# Снова открываем этот же файл, но в режиме "a" (append - добавление).
# Этот режим дописывает текст в самый конец, сохраняя то, что мы записали шагом ранее.
with open(filename, "a", encoding="utf-8") as file:
    file.write("Третья строка: Добавлено через 'a'.\n")