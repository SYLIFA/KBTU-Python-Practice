import os # Встроенный модуль для работы с файловой системой

# os.getcwd() возвращает строку с текущим путем (Current Working Directory).
# Это помогает понять, где именно сейчас работает наш скрипт.
print("Текущая директория:", os.getcwd())

new_dir = "test_dir" # Имя папки, которую мы хотим создать

# Проверяем, нет ли уже такой папки. Если попытаться создать существующую папку, программа выдаст ошибку.
if not os.path.exists(new_dir):
    # os.mkdir() создает ровно одну конечную папку. 
    os.mkdir(new_dir)
    print(f"Папка {new_dir} создана.")

nested_dirs = "parent_dir/child_dir" # Путь с вложенностью (папка внутри папки)

if not os.path.exists(nested_dirs):
    # os.makedirs() мощнее: она создает всю цепочку папок. 
    # Если 'parent_dir' не существует, программа создаст и её, и 'child_dir' внутри нее.
    os.makedirs(nested_dirs)
    print(f"Вложенные папки {nested_dirs} созданы.")

# os.listdir(".") возвращает список (list) всех файлов и папок в указанном месте.
# Точка "." в программировании означает "текущая папка".
print("Содержимое текущей папки:", os.listdir("."))