# Импортируем функцию reduce из модуля functools. 
# В старых версиях Python она была встроена, но сейчас её нужно вызывать отдельно.
from functools import reduce

# Создаем список целых чисел (тип integer)
numbers = [1, 2, 3, 4, 5, 6]
print(f"Исходный список: {numbers}")

# --- MAP (Трансформация) ---
# lambda x: x**2 — это анонимная функция. Она принимает 'x' и возвращает 'x' в квадрате.
# map() берет эту функцию и применяет её к КАЖДОМУ элементу списка 'numbers' по очереди.
# list() нужен, чтобы собрать результаты работы map обратно в полноценный список.
squared = list(map(lambda x: x**2, numbers))
print(f"map (возвели в квадрат): {squared}") # Выведет [1, 4, 9, 16, 25, 36]

# --- FILTER (Фильтрация) ---
# lambda x: x % 2 == 0 — проверяет, равен ли остаток от деления на 2 нулю (четное ли число).
# filter() пропускает через себя элементы. Если лямбда выдает True — элемент остается, если False — удаляется.
evens = list(filter(lambda x: x % 2 == 0, numbers))
print(f"filter (оставили только четные): {evens}") # Выведет [2, 4, 6]

# --- REDUCE (Свертка/Агрегация) ---
# lambda x, y: x * y — функция принимает ДВА аргумента и перемножает их.
# reduce() берет 1 и 2 (результат 2). Потом берет этот результат (2) и умножает на 3 (результат 6). И так далее.
product = reduce(lambda x, y: x * y, numbers)
print(f"reduce (перемножили все числа друг на друга): {product}") # Выведет 720