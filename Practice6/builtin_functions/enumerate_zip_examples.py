names = ["Alice", "Bob", "Charlie"] # Список строк с именами
scores = ["85", "92", "78"] # Внимание: оценки записаны как ТЕКСТ (в кавычках), а не как числа.

# --- ENUMERATE (Индексация) ---
print("--- Пример с enumerate ---")
# enumerate() при каждом шаге цикла выдает ПАРУ: (порядковый номер, значение).
# start=1 заставляет счетчик начать с 1, а не с 0 (как принято в программировании по умолчанию).
for index, name in enumerate(names, start=1):
    # Буква 'f' перед строкой позволяет вставлять переменные прямо в текст в фигурных скобках {}.
    print(f"Студент под номером {index} — это {name}")

# --- ПРЕОБРАЗОВАНИЕ ТИПОВ (Type Conversion) ---
print("\n--- Пример с zip и преобразованием типов ---")
# Это "генератор списка" (list comprehension). 
# Он берет каждую строку 's' из 'scores', превращает её в целое число с помощью int(s) и кладет в новый список.
int_scores = [int(s) for s in scores]

# --- ZIP (Параллельное слияние) ---
# zip() берет первый элемент из 'names' и первый из 'int_scores' и объединяет их. Затем вторые, и т.д.
for name, score in zip(names, int_scores):
    print(f"{name} получил {score} баллов.")

# --- ВСТРОЕННЫЕ ФУНКЦИИ АГРЕГАЦИИ ---
print("\n--- Статистика по оценкам ---")
# len() считает количество элементов в списке (длину списка)
print(f"Количество студентов (len): {len(int_scores)}")
# sum() складывает все числа в списке
print(f"Сумма всех баллов (sum): {sum(int_scores)}")
# min() и max() находят наименьшее и наибольшее значение
print(f"Минимальный балл (min): {min(int_scores)}")
print(f"Максимальный балл (max): {max(int_scores)}")
# sorted() сортирует список. Аргумент reverse=True делает сортировку по убыванию (от большего к меньшему).
print(f"Оценки по убыванию (sorted): {sorted(int_scores, reverse=True)}")